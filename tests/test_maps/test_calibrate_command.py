def test_rotation_is_composed_into_source_to_canonical_transform() -> None:
    from valoscribe.commands.minimap import (
        _compose_source_transform,
        orient_minimap_crop,
    )
    from valoscribe.maps.registration import RegistrationResult

    crop = np.zeros((4, 6, 3), dtype=np.uint8)
    _, crop_to_oriented = orient_minimap_crop(crop, "rotate_90_ccw")
    registration = RegistrationResult(
        aligned_minimap=np.zeros((10, 10, 3), dtype=np.uint8),
        transform_matrix=((2.0, 0.0, 10.0), (0.0, 2.0, 20.0)),
        confidence=0.9,
        alignment_error=0.1,
        method="fixed",
        failure_reason=None,
    )

    composed = _compose_source_transform(registration, crop_to_oriented)

    assert composed.transform_matrix == ((0.0, 2.0, 12.0), (-2.0, 0.0, 30.0))


