def write_test_inputs(tmp_path: Path) -> tuple[Path, Path, Path]:
    frame = np.zeros((100, 120, 3), dtype=np.uint8)
    cv2.rectangle(frame, (24, 34), (67, 77), (210, 210, 210), 2)
    cv2.circle(frame, (48, 54), 9, (80, 80, 80), -1)
    cv2.line(frame, (25, 75), (65, 36), (255, 255, 255), 2)
    video = tmp_path / "synthetic.avi"
    writer = cv2.VideoWriter(str(video), cv2.VideoWriter_fourcc(*"MJPG"), 1.0, (120, 100))
    assert writer.isOpened()
    writer.write(frame)
    writer.release()

    hud = tmp_path / "hud.json"
    hud.write_text(
        json.dumps(
            {
                "name": "synthetic-profile",
                "calibration_status": "validated",
                "frame_width": 120,
                "frame_height": 100,
                "minimap": {"x": 20, "y": 30, "width": 48, "height": 48},
                "regions": {},
            }
        ),
        encoding="utf-8",
    )
    map_image = tmp_path / "canonical.png"
    assert cv2.imwrite(str(map_image), frame[30:78, 20:68])
    map_config = tmp_path / "map.json"
    map_config.write_text(
        json.dumps(
            {
                "map_id": "synthetic-map",
                "map_name": "Synthetic",
                "canonical_minimap": {
                    "image_url": "https://example.invalid/synthetic.png",
                    "local_asset_path": map_image.name,
                    "sha256": hashlib.sha256(map_image.read_bytes()).hexdigest(),
                    "asset_version": "synthetic-test",
                    "patch_version": "not-applicable",
                    "provenance": "Generated by this offline test.",
                },
                "geometry_status": "pending",
            }
        ),
        encoding="utf-8",
    )
    return video, hud, map_config


def decoded_label_hashes(video: Path, map_config: Path) -> tuple[str, str]:
    capture = cv2.VideoCapture(str(video))
    assert capture.isOpened()
    ok, frame = capture.read()
    capture.release()
    assert ok
    map_data = json.loads(map_config.read_text(encoding="utf-8"))
    canonical_path = map_config.parent / map_data["canonical_minimap"]["local_asset_path"]
    canonical = cv2.imread(str(canonical_path))
    assert canonical is not None
    return decoded_image_sha256(frame), decoded_image_sha256(canonical)


def test_calibrate_command_writes_five_artifacts_and_marks_pending_map(
    tmp_path: Path,
) -> None:
    video, hud, map_config = write_test_inputs(tmp_path)
    output = tmp_path / "calibration"

    result = CliRunner().invoke(
        app,
        [
            "minimap",
            "calibrate",
            "--video",
            str(video),
            "--timestamp",
            "00:00:00.000",
            "--hud-config",
            str(hud),
            "--map-config",
            str(map_config),
            "--output",
            str(output),
        ],
    )

    assert result.exit_code == 1, result.output
    expected = {
        "frame.png",
        "minimap_crop.png",
        "registered_minimap.png",
        "alignment_overlay.png",
        "diagnostics.json",
    }
    assert expected <= {path.name for path in output.iterdir()}
    diagnostics = json.loads((output / "diagnostics.json").read_text(encoding="utf-8"))
    assert diagnostics["profile_id"] == "synthetic-profile"
    assert diagnostics["map_asset_version"] == "synthetic-test"
    assert diagnostics["timestamp_seconds"] == 0.0
    assert diagnostics["passed"] is False
    assert diagnostics["failure_reason"] == "map_geometry_pending"
    assert diagnostics["transform_matrix"] is not None
    assert diagnostics["confidence"] is not None
    assert diagnostics["alignment_error"] is not None


def test_cli_calibration_passes_with_validated_registration_and_landmarks(
    tmp_path: Path,
) -> None:
    video, hud, map_config = write_test_inputs(tmp_path)
    map_data = json.loads(map_config.read_text(encoding="utf-8"))
    map_data.update(
        geometry_status="validated",
        walkable_areas=[
            {"polygon_id": "walkable", "vertices": [
                {"x": 0.0, "y": 0.0}, {"x": 1.0, "y": 0.0},
                {"x": 1.0, "y": 1.0}, {"x": 0.0, "y": 1.0},
            ]}
        ],
        site_polygons=[
            {"polygon_id": "site", "vertices": [
                {"x": 0.4, "y": 0.4}, {"x": 0.6, "y": 0.4},
                {"x": 0.6, "y": 0.6}, {"x": 0.4, "y": 0.6},
            ]}
        ],
        spawn_polygons=[
            {"polygon_id": "spawn", "vertices": [
                {"x": 0.0, "y": 0.0}, {"x": 0.2, "y": 0.0},
                {"x": 0.2, "y": 0.2}, {"x": 0.0, "y": 0.2},
            ]}
        ],
        named_zones=[{
            "zone_id": "zone",
            "polygon": {"polygon_id": "zone", "vertices": [
                {"x": 0.0, "y": 0.0}, {"x": 0.3, "y": 0.0},
                {"x": 0.3, "y": 0.3}, {"x": 0.0, "y": 0.3},
            ]},
        }],
        orientation_rules=["synthetic identity orientation"],
        registration_thresholds={
            "minimum_confidence": 0.0,
            "maximum_alignment_error": 1.0,
            "maximum_landmark_error_px": 2.0,
        },
    )
    map_config.write_text(json.dumps(map_data), encoding="utf-8")

    source_hash, canonical_hash = decoded_label_hashes(video, map_config)
    landmarks = tmp_path / "reviewed-landmarks.json"
    points = [(24, 24), (8, 8), (40, 40), (24, 8), (8, 24)]
    landmarks.write_text(
        json.dumps(
            {
                "provenance": "synthetic identity correspondences for CLI acceptance",
                "source_frame_sha256": source_hash,
                "canonical_asset_sha256": canonical_hash,
                "landmarks": [
                    {
                        "landmark_id": f"point-{index}",
                        "source_crop_point": {"x": x, "y": y},
                        "canonical_point": {"x": x, "y": y},
                    }
                    for index, (x, y) in enumerate(points)
                ],
            }
        ),
        encoding="utf-8",
    )
    output = tmp_path / "accepted-calibration"

    result = CliRunner().invoke(
        app,
        [
            "minimap",
            "calibrate",
            "--video",
            str(video),
            "--timestamp",
            "00:00:00.000",
            "--hud-config",
            str(hud),
            "--map-config",
            str(map_config),
            "--output",
            str(output),
            "--landmarks",
            str(landmarks),
        ],
    )

    assert result.exit_code == 0, result.output
    diagnostics = json.loads((output / "diagnostics.json").read_text(encoding="utf-8"))
    assert diagnostics["passed"] is True
    assert diagnostics["failure_reason"] is None
    evaluation = diagnostics["landmark_evaluation"]
    assert evaluation["acceptance_threshold_configured"] is True
    assert evaluation["maximum_error_threshold_px"] == 2.0
    assert evaluation["passed"] is True
    assert evaluation["point_count"] == len(points)
    assert evaluation["per_point_errors"] == [
        {"landmark_id": f"point-{index}", "error_px": 0.0}
        for index in range(len(points))
    ]
    assert evaluation["maximum_error_px"] == 0.0


