def test_rotate_crop_transform_maps_original_coordinates_to_canonical() -> None:
    from valoscribe.commands.minimap import orient_minimap_crop

    crop = np.zeros((4, 6, 3), dtype=np.uint8)
    crop[1, 2] = (0, 0, 255)

    oriented, transform = orient_minimap_crop(crop, "rotate_90_ccw")

    assert oriented.shape == (6, 6, 3)
    destination = transform @ np.array([2.0, 1.0, 1.0])
    assert tuple(destination[:2]) == (2.0, 3.0)
    assert np.array_equal(oriented[3, 2], (0, 0, 255))


